// Retorna todos os anos disponíveis
export const getAvailableYears = () => {
  return Object.keys(worldCupData).map(Number).sort((a, b) => b - a);
};

// Retorna os times de um ano específico
export const getTeamsByYear = (year) => {
  const cup = worldCupData[year];
  if (!cup) return [];
  return Object.keys(cup.teams);
};

// Retorna os jogadores de um time específico
export const getPlayersByTeam = (year, teamName) => {
  const cup = worldCupData[year];
  if (!cup || !cup.teams[teamName]) return [];
  return cup.teams[teamName].players;
};

// Retorna um time aleatório de uma copa aleatória (para roleta)
export const getRandomTeam = () => {
  const years = getAvailableYears();
  const randomYear = years[Math.floor(Math.random() * years.length)];
  const teams = getTeamsByYear(randomYear);
  const randomTeam = teams[Math.floor(Math.random() * teams.length)];
  const players = getPlayersByTeam(randomYear, randomTeam);
  
  return {
    country: randomTeam,
    year: randomYear,
    flag: worldCupData[randomYear].country,
    players: players
  };
};
